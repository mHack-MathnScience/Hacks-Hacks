var UNVULGAR = Object.fromEntries(Object.entries(VULGAR).map(([k, v]) => [v, k]));
function gcd(a, b) {
	a = Math.abs(Math.trunc(a));
	b = Math.abs(Math.trunc(b));
	while (b) {
		const t = a % b;
		a = b;
		b = t;
	}
	return a || 1;
}
function lcm(a, b) {
	return Math.abs(a * b) / gcd(a, b);
}
function simplify(n, d) {
	if (d === 0) throw new Error("division by zero");
	if (d < 0) {
		n = -n;
		d = -d;
	}
	const g = gcd(n, d);
	return {
		n: n / g,
		d: d / g
	};
}
function formatSimple(n, d) {
	return VULGAR[`${n}/${d}`] ?? `${n}/${d}`;
}
function formatFrac(n, d, mixed = true) {
	const s = simplify(n, d);
	n = s.n;
	d = s.d;
	if (d === 1) return String(n);
	const sign = n < 0 ? "-" : "";
	n = Math.abs(n);
	if (mixed && n > d) {
		const w = Math.floor(n / d);
		const r = n % d;
		if (r === 0) return sign + String(w);
		return `${sign}${w} ${formatSimple(r, d)}`;
	}
	return sign + formatSimple(n, d);
}
function formatFracAscii(n, d, mixed = true) {
	const s = simplify(n, d);
	n = s.n;
	d = s.d;
	if (d === 1) return String(n);
	const sign = n < 0 ? "-" : "";
	n = Math.abs(n);
	if (mixed && n > d) {
		const w = Math.floor(n / d);
		const r = n % d;
		if (r === 0) return sign + String(w);
		return `${sign}${w} ${r}/${d}`;
	}
	return `${sign}${n}/${d}`;
}
function stripVulgar(text) {
	let out = text;
	for (const [glyph, ascii] of Object.entries(UNVULGAR)) out = out.split(glyph).join(ascii);
	return out;
}
function parseFrac(raw) {
	let s = stripVulgar(raw).trim().replace(/,/g, "");
	s = s.replace(/\$/g, "").replace(/\s+/g, " ");
	if (!s) return null;
	const mixed = s.match(/^(-)?(\d+)\s+(\d+)\s*\/\s*(\d+)$/);
	if (mixed) {
		const sign = mixed[1] ? -1 : 1;
		const w = Number(mixed[2]);
		const n = Number(mixed[3]);
		const d = Number(mixed[4]);
		if (!d) return null;
		return simplify(sign * (w * d + n), d);
	}
	const frac = s.match(/^(-)?(\d+)\s*\/\s*(\d+)$/);
	if (frac) return simplify((frac[1] ? -1 : 1) * Number(frac[2]), Number(frac[3]));
	if (/^-?\d+(\.\d+)?$/.test(s)) {
		const num = Number(s);
		if (!Number.isFinite(num)) return null;
		if (Number.isInteger(num)) return {
			n: num,
			d: 1
		};
		const den = 10 ** (s.split(".")[1] ?? "").length;
		return simplify(Math.round(num * den), den);
	}
	return null;
}
function fracsEqual(a, b) {
	const pa = parseFrac(a);
	const pb = parseFrac(b);
	if (pa && pb) return pa.n * pb.d === pb.n * pa.d;
	return stripVulgar(a).trim() === stripVulgar(b).trim();
}
