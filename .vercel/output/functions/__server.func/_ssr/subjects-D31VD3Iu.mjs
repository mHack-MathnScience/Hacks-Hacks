function nearbyInts(n, extras = []) {
	const set = /* @__PURE__ */ new Set();
	for (const d of [
		1,
		2,
		3,
		4,
		5,
		6,
		8,
		10,
		12,
		15,
		20,
		25,
		50,
		100,
		...extras
	]) {
		if (n - d > 0) set.add(n - d);
		set.add(n + d);
	}
	if (n > 1) set.add(n * 2);
	if (n % 2 === 0) set.add(n / 2);
	set.delete(n);
	return [...set];
}
