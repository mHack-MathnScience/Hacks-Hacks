function mc(teks, stem, correct, wrong, explanation, extra) {
	const seen = /* @__PURE__ */ new Set([correct]);
	const distractors = [];
	for (const w of shuffle(wrong)) {
		if (!w || seen.has(w)) continue;
		seen.add(w);
		distractors.push(w);
		if (distractors.length === 3) break;
	}
	if (distractors.length === 0) return input(teks, stem, correct, explanation, extra);
	const choices = shuffle([correct, ...distractors]).map((text, i) => ({
		id: LETTERS[i],
		text
	}));
	const correctId = choices.find((c) => c.text === correct).id;
	return {
		id: uid(),
		teks,
		stem,
		kind: "mc",
		choices,
		correct: correctId,
		explanation,
		visual: extra?.visual,
		expression: extra?.expression
	};
}
